#!/usr/bin/env node

// CU-203: derive the relay payload allowlist from the artifact that is actually deployed.
//
// The relay accepts a meta invocation only when its operation is one the deployed Abstract
// Account core exports, and it pays for that invocation from the operator WIF. When the list
// was typed by hand it kept naming `executeUnified` and `executeUnifiedByAddress` — entrypoints
// no deployed manifest and no contract source defines — so such a request passed validation and
// died later in simulation with an error that hid the cause.
//
// Fail closed: an unreadable, unparsable or execution-less manifest is a hard failure that
// leaves the shipped module untouched, never an empty allowlist (an empty allowlist would let
// the helper's `includes` check decide nothing, and never a list that allows everything).
//
// Usage:
//   node scripts/generate-relay-operations.mjs                 # rewrite the shipped module
//   NEOOS_RELAY_OPERATIONS_STDOUT=1 node scripts/generate-relay-operations.mjs   # print it
//   NEOOS_RELAY_OPERATIONS_MANIFEST=<path> node scripts/generate-relay-operations.mjs
//   node scripts/generate-relay-operations.mjs --manifest <path>

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DEFAULT_MANIFEST = path.join(ROOT, 'contracts', 'build', 'UnifiedSmartWalletV3.manifest.json');
const TARGET = path.join(ROOT, 'frontend', 'api', 'relayOperations.generated.js');

function resolveManifestPath() {
  const args = process.argv.slice(2);
  const flagIndex = args.indexOf('--manifest');
  if (flagIndex !== -1) {
    const value = args[flagIndex + 1];
    if (!value) fail('--manifest needs a path');
    return path.resolve(value);
  }
  return path.resolve(process.env.NEOOS_RELAY_OPERATIONS_MANIFEST || DEFAULT_MANIFEST);
}

function fail(message) {
  console.error(`[relay operations] ${message}`);
  process.exit(1);
}

function readDeployedExecutionMethods(manifestPath) {
  let raw;
  try {
    raw = fs.readFileSync(manifestPath, 'utf8');
  } catch (error) {
    fail(`cannot read the deployed manifest at ${manifestPath}: ${error?.message || error}`);
  }

  let manifest;
  try {
    manifest = JSON.parse(raw);
  } catch (error) {
    fail(`the deployed manifest at ${manifestPath} is not valid JSON: ${error?.message || error}`);
  }

  const methods = manifest?.abi?.methods;
  if (!Array.isArray(methods)) {
    fail(`the deployed manifest at ${manifestPath} declares no abi.methods array`);
  }

  const names = methods
    .map((method) => (typeof method?.name === 'string' ? method.name.trim() : ''))
    .filter((name) => name.startsWith('execute'));

  if (names.length === 0) {
    fail(`the deployed manifest at ${manifestPath} exports no execute* method; refusing to emit an allowlist that decides nothing`);
  }

  const unique = [...new Set(names)].sort();
  if (unique.length !== names.length) {
    fail(`the deployed manifest at ${manifestPath} declares duplicate execute* method names`);
  }
  const contractName = typeof manifest?.name === 'string' && manifest.name.trim()
    ? manifest.name.trim()
    : path.basename(manifestPath).replace(/\.manifest\.json$/, '');
  return { operations: unique, contractName };
}

function renderModule(operations, { manifestPath, contractName }) {
  const relativeManifest = path.relative(ROOT, manifestPath).split(path.sep).join('/');
  const body = operations.map((name) => `  '${name}',`).join('\n');
  return `// Generated by scripts/generate-relay-operations.mjs from ${relativeManifest} — do not hand-edit.
// The relay funds meta invocations from the operator WIF, so the operations it will accept are
// exactly the execution surface the deployed ${contractName} artifact exports. A name that is not
// in that ABI is not relayable, and this list is regenerated whenever the artifact changes.
export const ALLOWED_RELAY_META_OPERATIONS = Object.freeze([
${body}
]);
`;
}

const manifestPath = resolveManifestPath();
const { operations, contractName } = readDeployedExecutionMethods(manifestPath);
const source = renderModule(operations, { manifestPath, contractName });

if (process.env.NEOOS_RELAY_OPERATIONS_STDOUT === '1') {
  process.stdout.write(source);
} else {
  fs.writeFileSync(TARGET, source);
  console.log(`[relay operations] wrote ${path.relative(ROOT, TARGET)} with ${operations.length} deployed operations: ${operations.join(', ')}`);
}
